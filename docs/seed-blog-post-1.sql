## Typical Campaign Durations

**OOH advertising in Rewari Haryana** is available on the following booking cycles:

**1 Month** — The standard minimum for most formats. Suitable for product launches, event announcements, and short-burst awareness campaigns. Rates are highest per day at this duration but appropriate for time-limited campaigns where presence at a specific moment matters more than sustained frequency.

**3 Months** — The most popular campaign duration. Three months provides sufficient frequency to build genuine brand recall with the target audience while attracting a meaningful rate improvement over monthly cycles. Recommended as the starting point for first-time advertisers.

**6 Months** — Ideal for sustained brand-building campaigns. Half-year bookings guarantee continuous location occupancy and command significantly better rates than monthly cycles. Popular with real estate developers, NBFC and banking brands, and educational institutions with ongoing district-level awareness goals.

**12 Months** — Annual bookings are the most cost-efficient and are used by brands with an ongoing local presence requirement — financial institutions, telecom operators, and real estate projects with multi-month sales cycles. An annual booking effectively locks in a prime location and eliminates the re-booking overhead of shorter cycles.

