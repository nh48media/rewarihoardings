**Dual carriageway reach.** A gantry panel on a two-carriageway road faces traffic from both directions. A single gantry booking delivers impressions to vehicles traveling in both directions simultaneously — effectively two audience streams from one placement.

### When to Choose a Gantry
- Junction dominance campaigns at Rewari's busiest intersections
