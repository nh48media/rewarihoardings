## Unipole: When Height and Distance Win

### Core Strengths

**Highway-speed visibility.** On NH-48, vehicles travel at 70 to 90 km/h. A driver needs to register a brand from 400 to 600 metres away — before they can react, change lane, or look elsewhere. A unipole at the [NH-48 Entry Point](/locality/nh-48-entry-point) makes this possible. A roadside hoarding at the same location is obscured by other vehicles, trees, and roadside structures long before a driver gets close enough to read it.

**Long sightline on open roads.** In the open approach zones near Rewari on NH-48, nothing obstructs a 40 to 60 ft unipole panel. It is visible from enormous distances in both directions — reaching vehicles on approach and those departing the city. This gives a unipole more than double the effective impression window of a ground-level hoarding at the same location.

**Maximum single-placement reach.** A prime NH-48 unipole delivers more daily impressions from a single placement than almost any city-centre format combination in Rewari.

### When to Choose a Unipole
