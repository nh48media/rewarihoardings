## The Core Difference

A **unipole** is a single tall steel pole (25 to 60 feet high) with a large display panel at the top. Its defining characteristic is **height** — the panel rises above all roadside obstructions and is visible from 400 to 800 metres away, long before a driver reaches the location.

A **gantry** spans the full width of the road at 15 to 25 feet overhead. Its defining characteristic is **unavoidability** — every vehicle on the carriageway must physically pass beneath it and engage with the display. There is no line-of-sight avoidance possible.

Both are premium large-format OOH formats available in Rewari. The right choice depends on what you need the format to do for your specific campaign.

